#!/usr/bin/env bash
# ============================================================
# bootstrap.sh — recreates the ENTIRE "What Is The Move" project
# with its correct folder structure (src/app, src/components,
# src/lib, plus root config files) from a single embedded archive.
#
# Why this exists: GitHub's mobile/web file uploader flattens
# folder structure when you drag files in from a phone. This
# script sidesteps that entirely — it never goes through that
# uploader. You upload/paste this ONE file into a browser coding
# environment that has a terminal (GitHub Codespaces, Gitpod,
# StackBlitz, CodeSandbox, Replit, etc.), run it once, and it
# writes every file to its correct nested path itself, then
# commits and pushes.
#
# HOW TO USE (do this from your iPhone, in Safari):
#   1. On github.com, create a new EMPTY repository (no README,
#      no .gitignore, no license — just the bare repo).
#   2. Open a Codespace on that repo:
#      github.com -> your new repo -> green "Code" button ->
#      "Codespaces" tab -> "Create codespace on main".
#      (This opens a full browser-based VS Code + terminal —
#      works in mobile Safari.)
#   3. In the Codespace's file explorer, use the "Upload" action
#      (the icon at the top of the file explorer, or right-click
#      -> Upload...) to upload THIS ONE FILE (bootstrap.sh).
#      Uploading a single file cannot be flattened — there's
#      nothing to flatten.
#   4. Open the terminal in the Codespace (it's usually already
#      open at the bottom; if not: menu -> Terminal -> New Terminal)
#      and run:
#        bash bootstrap.sh
#   5. That's it. The script recreates every file and folder,
#      then commits and pushes automatically. Refresh the file
#      explorer to see the full src/app, src/components, src/lib
#      tree.
#
# This script does NOT change the app itself in any way — it only
# reconstructs the exact same project you already had, faithfully.
# ============================================================

